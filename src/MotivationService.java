public final class MotivationService {

    private MotivationService() {
    }

    public static String getAdvice(int score) {
        switch (score) {
            case 1:
                return "Даже один балл — это начало. Сделай сегодня один маленький шаг вперёд.";
            case 2:
                return "Ты уже держишься. Маленький шаг сегодня создаст движение завтра.";
            case 3:
                return "Начни с самого простого действия — и постепенно станет легче.";
            case 4:
                return "У тебя уже есть силы расти. Продолжай двигаться в своём темпе.";
            case 5:
                return "Хорошая середина: сохрани спокойствие и сделай ещё один уверенный шаг.";
            case 6:
                return "Уже есть заметный подъём. Используй его для небольшого важного дела.";
            case 7:
                return "Отличный настрой! Пусть он поможет тебе приблизиться к цели.";
            case 8:
                return "Ты на хорошем уровне. Действуй смело — у тебя всё получится.";
            case 9:
                return "Почти максимум! Сохрани эту энергию и поделись ею с другими.";
            case 10:
                return "Прекрасное настроение! Пусть сегодня всё получается легко и с удовольствием.";
            default:
                return "Ничего страшного, если настроение отличается от стандартного, может так даже лучше.";
        }
    }

    public static String getShortState(int score) {
        if (score <= 2) return "Тяжёлый день";
        if (score <= 4) return "Ниже обычного";
        if (score <= 6) return "Спокойный день";
        if (score <= 8) return "Хороший настрой";
        return "Отличное состояние";
    }
}
